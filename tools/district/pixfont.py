def width(text, scale=1, spacing=1):
    w = 0
    for ch in text:
        w += (len(G.get(ch, G[' '])[0]) + spacing) * scale
    return max(0, w - spacing * scale)

def draw(d, x, y, text, color, scale=1, spacing=1, bold=False, shadow=None):
    """Draw text with ImageDraw d at x,y (top-left); returns width."""
    for pass_ in ([shadow, color] if shadow else [color]):
        off = 1 if (shadow and pass_ is shadow) else 0
        cx = x
        for ch in text:
            rows = G.get(ch, G[' '])
            for j, row in enumerate(rows):
                for i, c in enumerate(row):
                    if c == '#':
                        px, py = cx + i * scale + off, y + j * scale + off
                        d.rectangle([px, py, px + scale - 1 + (1 if bold else 0), py + scale - 1], fill=pass_)
            cx += (len(rows[0]) + spacing) * scale
    return cx - x
